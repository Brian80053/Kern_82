module Kern82.Runtime (runtime) where

import Data.List (intercalate)
import Kern82.Charset (extendedCodePoints)

runtime :: String
runtime = unlines
  [ "#include <stdint.h>"
  , "#include <stdbool.h>"
  , "#include <stdio.h>"
  , "#include <stdlib.h>"
  , "#include <string.h>"
  , "#include <ctype.h>"
  , "#include <errno.h>"
  , "#include <math.h>"
  , "#include <limits.h>"
  , "#include <stddef.h>"
  , ""
  , "#if CHAR_BIT != 8"
  , "#error Kern82 requires 8-bit bytes"
  , "#endif"
  , "typedef char k_require_32_bit_float[(sizeof(float) == 4) ? 1 : -1];"
  , "typedef struct k_lifetime { int state; } k_lifetime;"
  , "typedef struct { void *base; size_t count; size_t offset; size_t element_size; k_lifetime *life; bool arithmetic; } k_pointer;"
  , "typedef struct { void (*code)(void); } k_function_pointer;"
  , "enum { K_LIVE_LOCAL = 1, K_LIVE_GLOBAL = 2, K_LIVE_DYNAMIC = 3, K_DEAD_LOCAL = 4, K_FREED = 5 };"
  , ""
  , "void k_fail(const char *message, int line, int column) {"
  , "    fprintf(stderr, \"Kern82 runtime error at %d:%d: %s\\n\", line, column, message);"
  , "    exit(1);"
  , "}"
  , ""
  , "int64_t k_range(int64_t value, int64_t low, int64_t high, int line, int column) {"
  , "    if (value < low || value > high) k_fail(\"integer overflow or cast out of range\", line, column);"
  , "    return value;"
  , "}"
  , ""
  , "k_lifetime *k_lifetime_local(int line, int column) {"
  , "    k_lifetime *life = (k_lifetime *)malloc(sizeof *life);"
  , "    if (life == NULL) k_fail(\"lifetime metadata allocation failure\", line, column);"
  , "    life->state = K_LIVE_LOCAL;"
  , "    return life;"
  , "}"
  , ""
  , "void k_lifetime_end(k_lifetime *life) {"
  , "    if (life != NULL && life->state == K_LIVE_LOCAL) life->state = K_DEAD_LOCAL;"
  , "}"
  , ""
  , "k_pointer k_null_pointer(void) {"
  , "    k_pointer result = {NULL, 0, 0, 0, NULL, false};"
  , "    return result;"
  , "}"
  , ""
  , "k_function_pointer k_null_function_pointer(void) {"
  , "    k_function_pointer result = {NULL};"
  , "    return result;"
  , "}"
  , ""
  , "k_function_pointer k_function_pointer_make(void (*code)(void)) {"
  , "    k_function_pointer result = {code};"
  , "    return result;"
  , "}"
  , ""
  , "void k_check_function_pointer(k_function_pointer pointer, int line, int column) {"
  , "    if (pointer.code == NULL) k_fail(\"NULL function pointer call\", line, column);"
  , "}"
  , ""
  , "k_pointer k_pointer_make(void *base, size_t count, size_t offset, size_t element_size, k_lifetime *life, bool arithmetic) {"
  , "    k_pointer result = {base, count, offset, element_size, life, arithmetic};"
  , "    return result;"
  , "}"
  , ""
  , "void k_check_pointer(k_pointer pointer, int line, int column) {"
  , "    if (pointer.life == NULL) k_fail(\"NULL pointer dereference\", line, column);"
  , "    if (pointer.life->state == K_DEAD_LOCAL) k_fail(\"dead storage or dangling pointer access\", line, column);"
  , "    if (pointer.life->state == K_FREED) k_fail(\"use after free\", line, column);"
  , "    if (pointer.base == NULL || pointer.offset >= pointer.count) k_fail(\"invalid pointer descriptor\", line, column);"
  , "}"
  , ""
  , "void *k_pointer_address(k_pointer pointer, int line, int column) {"
  , "    k_check_pointer(pointer, line, column);"
  , "    return (void *)((unsigned char *)pointer.base + pointer.offset * pointer.element_size);"
  , "}"
  , ""
  , "k_pointer k_pointer_checked(k_pointer pointer, int line, int column) {"
  , "    k_check_pointer(pointer, line, column);"
  , "    return pointer;"
  , "}"
  , ""
  , "k_pointer k_pointer_add(k_pointer pointer, int64_t delta, int line, int column) {"
  , "    size_t next;"
  , "    k_check_pointer(pointer, line, column);"
  , "    if (!pointer.arithmetic) k_fail(\"pointer arithmetic is not supported for this storage region\", line, column);"
  , "    if (delta < 0) {"
  , "        uint64_t magnitude = (uint64_t)(-(delta + 1)) + UINT64_C(1);"
  , "        if (magnitude > (uint64_t)pointer.offset) k_fail(\"pointer arithmetic out of bounds\", line, column);"
  , "        next = pointer.offset - (size_t)magnitude;"
  , "    } else {"
  , "        if ((uint64_t)delta >= (uint64_t)(pointer.count - pointer.offset)) k_fail(\"pointer arithmetic out of bounds\", line, column);"
  , "        next = pointer.offset + (size_t)delta;"
  , "    }"
  , "    pointer.offset = next;"
  , "    return pointer;"
  , "}"
  , ""
  , "int64_t k_pointer_subtract(k_pointer left, k_pointer right, int line, int column) {"
  , "    k_check_pointer(left, line, column);"
  , "    k_check_pointer(right, line, column);"
  , "    if (!left.arithmetic || !right.arithmetic || left.life != right.life || left.base != right.base || left.element_size != right.element_size)"
  , "        k_fail(\"invalid pointer subtraction\", line, column);"
  , "    return left.offset >= right.offset ? (int64_t)(left.offset - right.offset) : -(int64_t)(right.offset - left.offset);"
  , "}"
  , ""
  , "k_pointer k_allocate(int64_t count, size_t element_size, int line, int column) {"
  , "    k_pointer result;"
  , "    k_lifetime *life;"
  , "    void *storage;"
  , "    if (count <= 0 || (uint64_t)count > (uint64_t)(SIZE_MAX / element_size))"
  , "        k_fail(\"allocation count or size error\", line, column);"
  , "    storage = malloc((size_t)count * element_size);"
  , "    if (storage == NULL) k_fail(\"allocation failure\", line, column);"
  , "    life = (k_lifetime *)malloc(sizeof *life);"
  , "    if (life == NULL) { free(storage); k_fail(\"allocation failure\", line, column); }"
  , "    life->state = K_LIVE_DYNAMIC;"
  , "    result = k_pointer_make(storage, (size_t)count, 0, element_size, life, true);"
  , "    return result;"
  , "}"
  , ""
  , "void k_free_pointer(k_pointer pointer, int line, int column) {"
  , "    if (pointer.life == NULL) return;"
  , "    if (pointer.life->state == K_FREED) k_fail(\"double free\", line, column);"
  , "    if (pointer.life->state != K_LIVE_DYNAMIC) k_fail(\"attempt to free non-dynamic storage\", line, column);"
  , "    if (pointer.offset != 0) k_fail(\"attempt to free non-base allocation pointer\", line, column);"
  , "    free(pointer.base);"
  , "    pointer.life->state = K_FREED;"
  , "}"
  , ""
  , "float k_float(float value, int line, int column) {"
  , "    if (!isfinite((double)value)) k_fail(\"non-finite floating result\", line, column);"
  , "    return value;"
  , "}"
  , ""
  , "int64_t k_from_float(float value, int64_t low, int64_t high, int line, int column) {"
  , "    double truncated = trunc((double)value);"
  , "    if (!isfinite((double)value) || truncated < (double)low || truncated > (double)high)"
  , "        k_fail(\"floating cast out of range\", line, column);"
  , "    return (int64_t)truncated;"
  , "}"
  , ""
  , "int64_t k_div(int64_t a, int64_t b, bool remainder, int line, int column) {"
  , "    if (b == 0) k_fail(\"division by zero\", line, column);"
  , "    return remainder ? a % b : a / b;"
  , "}"
  , ""
  , "float k_fdiv(float a, float b, int line, int column) {"
  , "    if (b == 0.0f) k_fail(\"division by zero\", line, column);"
  , "    return k_float(a / b, line, column);"
  , "}"
  , ""
  , "int64_t k_bits(uint32_t value, int width) {"
  , "    uint64_t modulus = UINT64_C(1) << width;"
  , "    uint64_t v = (uint64_t)value & (modulus - 1);"
  , "    return v >= modulus / 2 ? (int64_t)v - (int64_t)modulus : (int64_t)v;"
  , "}"
  , ""
  , "int64_t k_shift(int64_t value, int64_t amount, int width, bool left, int line, int column) {"
  , "    int64_t factor;"
  , "    if (amount < 0 || amount >= width) k_fail(\"invalid shift count\", line, column);"
  , "    factor = INT64_C(1) << (unsigned)amount;"
  , "    if (left) return value * factor;"
  , "    /* Arithmetic right shift, explicitly defined also for negative inputs. */"
  , "    return value >= 0 ? value / factor : -((-value + factor - 1) / factor);"
  , "}"
  , ""
  , "size_t k_index(int64_t index, int64_t length, int line, int column) {"
  , "    if (index < 0 || index >= length) k_fail(\"array index out of bounds\", line, column);"
  , "    return (size_t)index;"
  , "}"
  , ""
  , "int k_input_char(int line, int column) {"
  , "    int ch = getchar();"
  , "    if (ch == EOF && ferror(stdin)) k_fail(\"input stream read error\", line, column);"
  , "    return ch;"
  , "}"
  , ""
  , "const char *k_token(int line, int column) {"
  , "    static char buffer[256];"
  , "    size_t size = 0;"
  , "    int ch;"
  , "    do { ch = k_input_char(line, column); } while (ch != EOF && isspace((unsigned char)ch));"
  , "    if (ch == EOF) return NULL;"
  , "    while (ch != EOF && !isspace((unsigned char)ch)) {"
  , "        if (size + 1 >= sizeof buffer) k_fail(\"input token exceeds 255 bytes\", line, column);"
  , "        if (ch == 0) k_fail(\"NUL in input token\", line, column);"
  , "        buffer[size++] = (char)ch;"
  , "        ch = k_input_char(line, column);"
  , "    }"
  , "    buffer[size] = '\\0';"
  , "    return buffer;"
  , "}"
  , ""
  , "int64_t k_parse_int(const char *token, int64_t low, int64_t high, int line, int column) {"
  , "    char *end;"
  , "    long long value;"
  , "    errno = 0;"
  , "    value = strtoll(token, &end, 10);"
  , "    if (errno == ERANGE || end == token || *end != '\\0') k_fail(\"invalid integer input\", line, column);"
  , "    return k_range((int64_t)value, low, high, line, column);"
  , "}"
  , ""
  , "float k_parse_float(const char *token, int line, int column) {"
  , "    char *end;"
  , "    float value;"
  , "    errno = 0;"
  , "    value = strtof(token, &end);"
  , "    if (errno == ERANGE || end == token || *end != '\\0') k_fail(\"invalid floating input\", line, column);"
  , "    return k_float(value, line, column);"
  , "}"
  , ""
  , "bool k_parse_bool(const char *token, int line, int column) {"
  , "    if (strcmp(token, \"WAHR\") == 0) return true;"
  , "    if (strcmp(token, \"FALSCH\") == 0) return false;"
  , "    k_fail(\"BOOL input must be WAHR or FALSCH\", line, column);"
  , "    return false;"
  , "}"
  , ""
  , "static const uint32_t k_upper_unicode[128] = {"
  , "    " ++ intercalate "," (map show extendedCodePoints)
  , "};"
  , ""
  , "void k_put_unicode(uint32_t value) {"
  , "    if (value < 0x80) putchar((int)value);"
  , "    else if (value < 0x800) { putchar(0xc0 | (int)(value >> 6)); putchar(0x80 | (int)(value & 0x3f)); }"
  , "    else { putchar(0xe0 | (int)(value >> 12)); putchar(0x80 | (int)((value >> 6) & 0x3f)); putchar(0x80 | (int)(value & 0x3f)); }"
  , "}"
  , ""
  , "void k_put_char(uint8_t value) {"
  , "    k_put_unicode(value < 128 ? value : k_upper_unicode[value - 128]);"
  , "}"
  , ""
  , "void k_put_string(const uint8_t *value) {"
  , "    while (*value != 0) k_put_char(*value++);"
  , "}"
  , ""
  , "uint32_t k_decode_utf8(const unsigned char *s, size_t *used, int line, int column) {"
  , "    uint32_t value;"
  , "    if (s[0] < 0x80) { *used = 1; return s[0]; }"
  , "    if (s[0] >= 0xc2 && s[0] <= 0xdf && (s[1] & 0xc0) == 0x80) {"
  , "        *used = 2; return ((uint32_t)(s[0] & 0x1f) << 6) | (uint32_t)(s[1] & 0x3f);"
  , "    }"
  , "    if (s[0] >= 0xe0 && s[0] <= 0xef && (s[1] & 0xc0) == 0x80 && (s[2] & 0xc0) == 0x80) {"
  , "        value = ((uint32_t)(s[0] & 0x0f) << 12) | ((uint32_t)(s[1] & 0x3f) << 6) | (uint32_t)(s[2] & 0x3f);"
  , "        if (value >= 0x800 && !(value >= 0xd800 && value <= 0xdfff)) { *used = 3; return value; }"
  , "    }"
  , "    k_fail(\"CHAR input is not valid Kern 82 text encoded as UTF-8\", line, column);"
  , "    *used = 0; return 0;"
  , "}"
  , ""
  , "uint8_t k_parse_char(const char *text, int line, int column) {"
