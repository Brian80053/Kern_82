  , "    size_t used, i;"
  , "    uint32_t value = k_decode_utf8(token, &used, line, column);"
  , "    if (token[used] != 0) k_fail(\"CHAR input must contain exactly one Kern 82 character\", line, column);"
  , "    if (value < 128) return (uint8_t)value;"
  , "    for (i = 0; i < 128; ++i) if (k_upper_unicode[i] == value) return (uint8_t)(i + 128);"
  , "    k_fail(\"CHAR input is outside the Kern 82 character set\", line, column);"
  , "    return 0;"
  , "}"
  , ""
  , "size_t k_kette_index(int64_t index, size_t length, int line, int column) {"
  , "    if (index < 0 || (uint64_t)index >= (uint64_t)length)"
