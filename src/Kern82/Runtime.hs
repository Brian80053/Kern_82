  , "    return (size_t)index;"
  , "}"
  , ""
  , "uint8_t k_kette_store(uint8_t *data, size_t *length, size_t capacity, int64_t index, uint8_t value, int line, int column) {"
  , "    size_t checked = k_kette_write_index(index, *length, capacity, line, column);"
  , "    data[checked] = value;"
  , "    if (checked == *length) ++*length;"
  , "    return value;"
  , "}"
  , ""
  , "uint8_t k_kern_byte(uint32_t value, int line, int column) {"
  , "    size_t i;"
  , "    if (value < 128) return (uint8_t)value;"
  , "    for (i = 0; i < 128; ++i) if (k_upper_unicode[i] == value) return (uint8_t)(i + 128);"
  , "    k_fail(\"KETTE input character is outside the Kern 82 character set\", line, column);"
  , "    return 0;"
  , "}"
  , ""
  , "/* Decode one token directly into fixed-capacity storage. No temporary"
  , "   dynamic string and no inherited 255-host-byte token limit. */"
  , "bool k_read_kette(uint8_t *data, size_t capacity, size_t *length, int line, int column) {"
  , "    size_t count = 0;"
  , "    int ch;"
  , "    do { ch = k_input_char(line, column); } while (ch != EOF && isspace((unsigned char)ch));"
  , "    if (ch == EOF) return false;"
  , "    while (ch != EOF && !isspace((unsigned char)ch)) {"
  , "        unsigned char encoded[4] = {0, 0, 0, 0};"
  , "        size_t needed, i, used;"
  , "        uint32_t value;"
  , "        if (ch == 0) k_fail(\"NUL in input token\", line, column);"
  , "        encoded[0] = (unsigned char)ch;"
  , "        if (encoded[0] < 0x80) needed = 1;"
  , "        else if (encoded[0] >= 0xc2 && encoded[0] <= 0xdf) needed = 2;"
  , "        else if (encoded[0] >= 0xe0 && encoded[0] <= 0xef) needed = 3;"
  , "        else { k_fail(\"invalid UTF-8 or character outside Kern 82 in KETTE input\", line, column); needed = 1; }"
  , "        for (i = 1; i < needed; ++i) {"
  , "            ch = k_input_char(line, column);"
  , "            if (ch == EOF || ((unsigned char)ch & 0xc0) != 0x80)"
  , "                k_fail(\"invalid UTF-8 in KETTE input\", line, column);"
  , "            encoded[i] = (unsigned char)ch;"
  , "        }"
  , "        value = k_decode_utf8(encoded, &used, line, column);"
  , "        if (used != needed) k_fail(\"invalid UTF-8 in KETTE input\", line, column);"
  , "        if (count == capacity) k_fail(\"KETTE input exceeds capacity\", line, column);"
  , "        data[count++] = k_kern_byte(value, line, column);"
  , "        ch = k_input_char(line, column);"
  , "    }"
  , "    *length = count;"
  , "    return true;"
  , "}"
